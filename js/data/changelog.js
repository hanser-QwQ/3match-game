/**
 * 比较两个 x.y.z 版本号：a 较新返回正数，相等返回 0，a 较旧返回负数。
 * 非标准写法按缺失段为 0 处理。
 */
export function compareVersions(a, b) {
  const pa = String(a || '').split('.').map((x) => parseInt(x, 10) || 0);
  const pb = String(b || '').split('.').map((x) => parseInt(x, 10) || 0);
  for (let i = 0; i < 3; i += 1) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d !== 0) return d;
  }
  return 0;
}
